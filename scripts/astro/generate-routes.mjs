#!/usr/bin/env node
/**
 * Generate src/pages/** from the App Router files in app/ (Phase 1 of
 * docs/EMDASH-MIGRATION-PLAN.md). Each Astro route is a thin wrapper: pages
 * render through src/rt/render.tsx; route handlers, opengraph-image, sitemap
 * and robots become endpoints. Re-run after adding or moving an app/ route:
 *   node scripts/astro/generate-routes.mjs
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const root = process.cwd();
const appDir = join(root, "app");
const pagesDir = join(root, "src", "pages");
const HEADER = "// Generated by scripts/astro/generate-routes.mjs — edit app/, then re-run.\n";
// Everything is prerendered on Node except the live editorial routes, which
// render on the Worker with a prerendered twin under /live-snapshot/.
const LIVE = JSON.parse(readFileSync(join(root, "src", "rt", "live-routes.json"), "utf8"));
const PRERENDER = "export const prerender = true;\n";

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(relative(appDir, p).split("\\").join("/"));
  }
  return out;
}

const files = walk(appDir);
const routeOf = (dir) => (dir === "." || dir === "" ? "/" : `/${dir}`);
const hasParams = (route) => route.includes("[");
const emitted = [];

function write(target, body) {
  const full = join(pagesDir, target);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, body);
  emitted.push(target);
}

rmSync(pagesDir, { recursive: true, force: true });

for (const f of files) {
  const dir = dirname(f);
  const route = routeOf(dir === "." ? "" : dir);
  const imp = `@/app/${f.replace(/\.tsx?$/, "")}`;

  if (f.endsWith("/page.tsx") || f === "page.tsx") {
    const target = route === "/" ? "index.astro" : `${route.slice(1)}.astro`;
    const paths = hasParams(route)
      ? `export async function getStaticPaths() {\n  return staticPaths(mod);\n}\n`
      : "";
    const live = LIVE[route];
    write(
      target,
      `---\n${HEADER}export const prerender = ${!live};\nimport * as mod from "${imp}";\nimport Document from "@/src/rt/Document.astro";\nimport { pathFor, renderPage, staticPaths } from "@/src/rt/render";\n\n${paths}const page = await renderPage(mod, ${JSON.stringify(route)}, Astro.params, pathFor(${JSON.stringify(route)}, Astro.params));\nif (page.kind === "redirect") return Astro.redirect(page.location, page.status);\nAstro.response.status = page.status;\n---\n<Document page={page} />\n`,
    );
    if (live) {
      write(
        `live-snapshot/${live}.astro`,
        `---\n${HEADER}${PRERENDER}import * as mod from "${imp}";\nimport Document from "@/src/rt/Document.astro";\nimport { renderSnapshot } from "@/src/rt/snapshot";\n\nconst page = await renderSnapshot(mod, ${JSON.stringify(route)}, ${JSON.stringify(live)});\nif (page.kind === "redirect") throw new Error("live routes cannot redirect");\n---\n<Document page={page} />\n`,
      );
    }
  } else if (f.endsWith("route.ts")) {
    // app/api/v1.json/route.ts -> src/pages/api/v1.json.ts
    write(
      `${route.slice(1)}.ts`,
      `${HEADER}${PRERENDER}import * as mod from "${imp}";\nimport { routeHandler, staticPaths } from "@/src/rt/endpoints";\n\n${hasParams(route) ? "export const getStaticPaths = () => staticPaths(mod);\n" : ""}export const GET = routeHandler(mod);\n`,
    );
  } else if (f.endsWith("opengraph-image.tsx")) {
    const target = route === "/" ? "opengraph-image.ts" : `${route.slice(1)}/opengraph-image.ts`;
    write(
      target,
      `${HEADER}${PRERENDER}import * as mod from "${imp}";\nimport { ogImageHandler, staticPaths } from "@/src/rt/endpoints";\n\n${hasParams(route) ? "export const getStaticPaths = () => staticPaths(mod);\n" : ""}export const GET = ogImageHandler(mod);\n`,
    );
  }
}

write("sitemap.xml.ts", `${HEADER}${PRERENDER}import sitemap from "@/app/sitemap";\nimport { sitemapHandler } from "@/src/rt/endpoints";\n\nexport const GET = sitemapHandler(sitemap);\n`);
// EmDash serves /sitemap-<collection>.xml unless the site defines it; editorial
// entries have no URLs of their own, so those sitemaps would list dead links.
write("sitemap-[collection].xml.ts", `${HEADER}export const prerender = false;\n\nexport const GET = () => new Response("Not found", { status: 404 });\n`);
write("robots.txt.ts", `${HEADER}${PRERENDER}import robots from "@/app/robots";\nimport { robotsHandler } from "@/src/rt/endpoints";\n\nexport const GET = robotsHandler(robots);\n`);
write(
  "404.astro",
  `---\n${HEADER}${PRERENDER}import Document from "@/src/rt/Document.astro";\nimport { renderNotFound } from "@/src/rt/render";\n\nconst page = await renderNotFound("/404");\nif (page.kind === "redirect") throw new Error("not-found cannot redirect");\nAstro.response.status = 404;\n---\n<Document page={page} />\n`,
);
for (const [name, type] of [["favicon.ico", "image/x-icon"], ["icon.svg", "image/svg+xml"], ["apple-icon.png", "image/png"]]) {
  write(`${name}.ts`, `${HEADER}${PRERENDER}import { appFileHandler } from "@/src/rt/endpoints";\n\nexport const GET = appFileHandler(${JSON.stringify(name)}, ${JSON.stringify(type)});\n`);
}

console.log(`Wrote ${emitted.length} routes to src/pages/`);
